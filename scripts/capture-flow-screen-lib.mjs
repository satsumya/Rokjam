/**
 * Shared Playwright capture logic for flow-map screens.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import {
  flowMapPath,
  loadManifest,
  parseFlowMapJourneys,
  saveManifest,
  syncFlowUpdatedAt,
  touchCapturedScreens,
} from './flow-map-manifest-utils.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

export const outDir = path.join(__dirname, '../assets/flow-screens');
export const publicDir = path.join(__dirname, '../public/flow-screens');
export const dimensionsFile = path.join(__dirname, '../src/constants/flowScreenDimensions.ts');
export const screensFile = path.join(__dirname, 'flow-map-screens.json');
export const defaultAppBase = process.env.FLOW_MAP_APP_URL ?? 'http://localhost:8081';

export const VIEWPORT_W = 360;
export const VIEWPORT_H = 780;

export function loadScreenList() {
  return JSON.parse(fs.readFileSync(screensFile, 'utf8'));
}

export function withFlowCapture(routePath) {
  const separator = routePath.includes('?') ? '&' : '?';
  return `${routePath}${separator}flowCapture=1`;
}

async function readPngSize(filePath) {
  const buf = await fs.promises.readFile(filePath);
  if (buf.length < 24) throw new Error(`Invalid PNG: ${filePath}`);
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

export async function captureOneScreen(page, screen, appBase = defaultAppBase) {
  const url = `${appBase}${withFlowCapture(screen.path)}`;
  const filePath = path.join(outDir, `${screen.id}.png`);

  await page.setViewportSize({ width: VIEWPORT_W, height: VIEWPORT_H });
  await page.goto(url, { waitUntil: 'networkidle', timeout: 30000 });
  await page.waitForTimeout(1800);

  await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
  await page.waitForTimeout(200);

  const finalHeight = await page.evaluate((minH) => {
    const measure = (el) => {
      const rect = el.getBoundingClientRect();
      const style = window.getComputedStyle(el);
      if (style.display === 'none' || style.visibility === 'hidden') return 0;
      let bottom = rect.bottom + window.scrollY;
      for (const child of el.children) {
        bottom = Math.max(bottom, measure(child));
      }
      return bottom;
    };
    return Math.min(Math.max(measure(document.body), minH), 5600);
  }, VIEWPORT_H);

  if (finalHeight > VIEWPORT_H) {
    await page.setViewportSize({ width: VIEWPORT_W, height: finalHeight });
    await page.waitForTimeout(400);
  }

  await page.screenshot({ path: filePath, type: 'png', fullPage: false });
  await fs.promises.copyFile(filePath, path.join(publicDir, `${screen.id}.png`));
  return readPngSize(filePath);
}

function readExistingDimensions() {
  if (!fs.existsSync(dimensionsFile)) return {};
  const content = fs.readFileSync(dimensionsFile, 'utf8');
  const match = content.match(/FLOW_SCREEN_DIMENSIONS[^=]*=\s*(\{[\s\S]*?\});/);
  if (!match) return {};
  return JSON.parse(match[1]);
}

export async function writeDimensionsFile(dimensions) {
  const ts = `/**
 * Pixel dimensions of captured PNGs — regenerated by flow-map capture.
 */
export const FLOW_SCREEN_DIMENSIONS: Record<string, { width: number; height: number }> = ${JSON.stringify(dimensions, null, 2)};

export function frameHeightForScreen(
  screenId: string,
  nodeWidth: number,
  minHeight: number,
  extraDimensions?: Record<string, { width: number; height: number }>,
): number {
  const dims = extraDimensions?.[screenId] ?? FLOW_SCREEN_DIMENSIONS[screenId];
  if (!dims?.width) return minHeight;
  const scaled = Math.round((dims.height / dims.width) * nodeWidth);
  return Math.max(minHeight, scaled);
}
`;
  await fs.promises.writeFile(dimensionsFile, ts);
}

export function screenIdsForFlow(flowId) {
  const journeys = parseFlowMapJourneys(fs.readFileSync(flowMapPath, 'utf8'));
  const ids = journeys[flowId];
  if (!ids?.length) throw new Error(`Unknown flow id: ${flowId}`);
  return ids;
}

export async function captureFlowScreens({
  screenIds,
  appBase = defaultAppBase,
  bumpLevel = null,
} = {}) {
  const allScreens = loadScreenList();
  const idSet = new Set(screenIds);
  const targets = allScreens.filter((s) => idSet.has(s.id));

  if (!targets.length) {
    throw new Error(`No matching screens for: ${screenIds.join(', ')}`);
  }

  const unknown = screenIds.filter((id) => !allScreens.some((s) => s.id === id));
  if (unknown.length) {
    throw new Error(`Unknown screen id(s): ${unknown.join(', ')}`);
  }

  await fs.promises.mkdir(outDir, { recursive: true });
  await fs.promises.mkdir(publicDir, { recursive: true });

  const { chromium } = await import('playwright');
  const browser = await chromium.launch();
  const page = await browser.newPage({
    viewport: { width: VIEWPORT_W, height: VIEWPORT_H },
    deviceScaleFactor: 2,
  });

  const captured = {};
  for (const screen of targets) {
    const size = await captureOneScreen(page, screen, appBase);
    captured[screen.id] = size;
  }

  await browser.close();

  const dimensions = { ...readExistingDimensions(), ...captured };
  await writeDimensionsFile(dimensions);

  const manifest = loadManifest();
  const capturedIds = targets.map((s) => s.id);
  touchCapturedScreens(manifest, capturedIds, bumpLevel ? { bump: true, level: bumpLevel } : {});
  syncFlowUpdatedAt(manifest, parseFlowMapJourneys(fs.readFileSync(flowMapPath, 'utf8')));
  saveManifest(manifest);

  const screens = capturedIds.map((id) => ({
    id,
    width: dimensions[id].width,
    height: dimensions[id].height,
    version: manifest.screens[id].version,
    updatedAt: manifest.screens[id].updatedAt,
  }));

  const flows = Object.keys(manifest.flows)
    .filter((flowId) => {
      const journeyScreens = parseFlowMapJourneys(fs.readFileSync(flowMapPath, 'utf8'))[flowId] ?? [];
      return journeyScreens.some((sid) => capturedIds.includes(sid));
    })
    .map((flowId) => ({
      id: flowId,
      version: manifest.flows[flowId].version,
      updatedAt: manifest.flows[flowId].updatedAt,
    }));

  return { screens, flows };
}
